<?php

return [

    /*
    |--------------------------------------------------------------------------
    | アプリケーションの名前
    |--------------------------------------------------------------------------
    |
    | 通知などで、フレームワークがアプリケーションの名前を出すときに使う。
    |
    */

    'name' => env('APP_NAME', 'Laravel'),

    // 画面やメールに出す、サイトの名前。日本語で書いてよい。書いていなければ空で、名前は出ない。
    // APP_NAMEは代わりに使わない。APP_NAMEは処理の中で使うサイトの識別名で、人に見せる名前ではないため。
    // APP_NAMEと分けているのは、LaravelがAPP_NAMEから、セッションのCookieやキャッシュの名前を
    // 英数字だけを残して作るため。APP_NAMEを日本語にすると、名前が「-session」のように空になり、
    // 同じドメインやDBに置いたほかのサイトとぶつかる。APP_NAMEは半角の英数字で書く
    'site_name' => (string) env('SITE_NAME', ''),

    /*
    |--------------------------------------------------------------------------
    | 動かしている環境
    |--------------------------------------------------------------------------
    |
    | 今の環境（production・localなど）。環境によって、使うサービスの設定を
    | 変えるときに見る。.envのAPP_ENVに書く。
    |
    */

    'env' => env('APP_ENV', 'production'),

    /*
    |--------------------------------------------------------------------------
    | デバッグモード
    |--------------------------------------------------------------------------
    |
    | trueにすると、エラーのときに詳しい内容とスタックトレースを画面に出す。
    | falseなら、決まった形の簡単なエラーの画面を出す。本番ではfalseにする。
    |
    */

    'debug' => (bool) env('APP_DEBUG', false),

    /*
    |--------------------------------------------------------------------------
    | アプリケーションのURL
    |--------------------------------------------------------------------------
    |
    | Artisanのコマンドの中でURLを作るときに使う。アプリケーションの
    | トップのURLを書く。
    |
    */

    'url' => env('APP_URL', 'http://localhost'),

    /*
    |--------------------------------------------------------------------------
    | タイムゾーン
    |--------------------------------------------------------------------------
    |
    | PHPの日付と日時の関数が使うタイムゾーン。
    |
    */

    'timezone' => 'Asia/Tokyo',

    /*
    |--------------------------------------------------------------------------
    | 言語
    |--------------------------------------------------------------------------
    |
    | 翻訳の関数が使う言語。翻訳の文言を用意した言語を書く。
    | fallback_localeは、その言語に文言が無いときに使う言語。
    | faker_localeは、テストやシーダーの見本のデータを作るときの言語。
    |
    */

    'locale' => env('APP_LOCALE', 'ja'),

    'fallback_locale' => env('APP_FALLBACK_LOCALE', 'en'),

    'faker_locale' => env('APP_FAKER_LOCALE', 'ja_JP'),

    /*
    |--------------------------------------------------------------------------
    | 暗号化の鍵
    |--------------------------------------------------------------------------
    |
    | Laravelの暗号化が使う鍵。暗号化した値を守るため、ランダムな32文字に
    | する。公開する前に、php artisan key:generateで作る。
    |
    | previous_keysには、鍵を替えたときの古い鍵をカンマで区切って書く。
    | 古い鍵で暗号化したCookieなどを、しばらく読めるようにするため。
    |
    */

    'cipher' => 'AES-256-CBC',

    'key' => env('APP_KEY'),

    'previous_keys' => [
        ...array_filter(
            explode(',', (string) env('APP_PREVIOUS_KEYS', ''))
        ),
    ],

    /*
    |--------------------------------------------------------------------------
    | メンテナンスモードの置き場所
    |--------------------------------------------------------------------------
    |
    | メンテナンスモードかどうかを、どこに記録するか。"cache"にすると、
    | 複数のサーバーでまとめて切り替えられる。
    |
    | 使える値："file"・"cache"・"array"
    |
    */

    'maintenance' => [
        'driver' => env('APP_MAINTENANCE_DRIVER', 'file'),
        'store' => env('APP_MAINTENANCE_STORE', 'database'),
    ],

];
