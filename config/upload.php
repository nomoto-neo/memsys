<?php

return [

    /*
    |--------------------------------------------------------------------
    | アップロードできるファイルの種類と大きさ
    |--------------------------------------------------------------------
    |
    | 画面からアップロードするファイル（App\Support\AjaxFileUpload）と、
    | CSVの取り込み（App\Support\CsvReader）で受け付けるファイルの条件。
    | サイト全体の方針として、プロジェクトごとにここで決める。
    | コーナーごとには変えない。
    |
    | 種類は拡張子で書く。拡張子だけでなく、ファイルの中身から見た種類も
    | 確かめる（Laravelのmimes）。
    |
    | 大きさの上限を上げるときは、サーバーのupload_max_filesizeと
    | post_max_sizeも、それ以上にしておく。
    |
    */

    // 画像の欄（一覧の画像・顔写真など）と、WYSIWYGの本文に入れる画像の種類。
    // 変えたら、エディタでファイルを選ぶときの絞り込み（resources/js/wysiwyg_suneditor.js・
    // wysiwyg_summernote.jsのACCEPT_IMAGE_TYPES）も合わせる
    'image_types' => ['jpg', 'jpeg', 'png', 'webp'],

    // 添付ファイルの欄の種類
    'attach_types' => ['pdf', 'doc', 'docx', 'xls', 'xlsx', 'csv', 'zip'],

    // 1ファイルの大きさの上限(KB)
    'max_kb' => 10240,

    // 画像1枚の画素数の上限。4000万画素は8000×5000くらいで、スマートフォンの写真は十分に収まる。
    // サーバーのメモリに余裕があっても、これを超える画像は受け付けない
    'max_image_pixels' => 40_000_000,

    // 取り込むCSVファイルの大きさの上限(KB)
    'csv_max_kb' => 10240,

];
