<?php

namespace Neobit\Core\Upload;

/**
 * アップロードしたファイルの保存先のディレクトリを決める規則。使う規則のクラスは、
 * config('upload.directory_rule')に書く。既定はDefaultUploadDirectory。
 * 保存・URL・削除・非公開のファイルの配信は、どれもUploadFilePath::directory()を通して
 * ここを呼ぶので、規則を差し替えれば全部が新しい保存先で動く。
 *
 * ■ 規則が守ること
 * - 1件ごとに専用のディレクトリにする。レコードを消すとき、フレームワークはディレクトリごと消すので、
 *   ほかの行のファイルが同じディレクトリや下のディレクトリにあると、一緒に消えてしまう
 * - モデルごとに分ける。会員とニュースで同じidがあっても、ぶつからないようにする
 * - 「..」や先頭の「/」を含めない。UploadFilePathが確かめて、含んでいれば例外にする
 * - 運用を始めた後に変えない。変えると、すでにあるファイルの場所とずれる。変えるときは、
 *   ファイルを移すマイグレーションが要る
 *
 * 受け取るのは、モデルのクラス名とidだけ。親のidだけが手元にある場面でも、レコードを
 * 読まずに使えるようにするため。そのため、レコードの中身（登録した日など）を使う規則は書けない。
 */
interface UploadDirectoryRule
{
    /** 保存先のディレクトリ。ディスクの中のパスで、末尾に「/」を付けない。例：news/000/000012 */
    public static function directory(string $ownerClass, int|string $ownerKey): string;
}
